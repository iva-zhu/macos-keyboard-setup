#!/usr/bin/env bash
# install.sh — deploy this repo into $HOME with GNU Stow.
#
#   ./install.sh              # asks a few questions, then symlinks everything
#   ./install.sh --dry-run    # show what would change, touch nothing
#   ./install.sh --no-prompt  # no questions, keep current values (scripting)
#
# Steps:
#   1. sanity checks (macOS, stow present)
#   2. optional `brew bundle --file=Brewfile`
#   3. asks for machine-local values; an empty answer keeps the shown default,
#      '-' clears the value (the feature is then switched off, no empty fields
#      end up in the configs)
#   4. writes ~/.config/setup.local.zsh (600) and
#      ~/.config/aerospace/browser.conf
#   5. moves aside whatever would conflict, to ~/.dotfiles-removed-<date>/
#   6. stow --no-folding, one package per app: zsh ghostty wm keys tools
#
# Package dirs mirror $HOME, so plain stow works too:
#   stow --no-folding -t ~ zsh ghostty wm keys tools
# Undo:  stow -D -t "$HOME" zsh ghostty wm keys tools
set -euo pipefail

REPO="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PACKAGES=(zsh ghostty wm keys tools)
BACKUP="$HOME/.dotfiles-removed-$(date +%Y%m%d)"
SETUP_FILE="$HOME/.config/setup.local.zsh"
BROWSER_FILE="$HOME/.config/aerospace/browser.conf"

DRY=0
PROMPT=1
for arg in "$@"; do
	case $arg in
	--dry-run) DRY=1 ;;
	--no-prompt) PROMPT=0 ;;
	-h | --help)
		sed -n '2,24p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
		exit 0
		;;
	*)
		say_unknown() { :; }
		echo "unknown option: $arg" >&2
		exit 2
		;;
	esac
done

say() { printf '%s\n' "$*"; }
run() { if ((DRY)); then say "  + $*"; else "$@"; fi; }

# ── 1. sanity ────────────────────────────────────────────────────────
[[ $OSTYPE == darwin* ]] || { say "this setup targets macOS"; exit 1; }
if ! command -v stow >/dev/null; then
	say "GNU Stow is missing. Install it first:  brew install stow"
	exit 1
fi

# ── 2. optional: Homebrew packages ───────────────────────────────────
if ((PROMPT && DRY == 0)) && command -v brew >/dev/null; then
	say ""
	read -r -p "Install Homebrew packages from Brewfile? [y/N] " yn || yn=""
	case $yn in
	[yY]*) brew bundle --file="$REPO/Brewfile" ;;
	*) say "  skipped" ;;
	esac
fi

# ── 3. current values become the defaults ────────────────────────────
cur_ssh="" cur_lan="" cur_browser="com.apple.Safari"
cur_port="11434" cur_tport="11112" cur_rtport="18080"
if [[ -r $SETUP_FILE ]]; then
	# shellcheck disable=SC1090
	eval "$(grep -E '^export (SSH_HOST|HOME_LAN_HOST|OLLAMA_LOCAL_PORT|OLLAMA_TUNNEL_PORT|ROUTER_TUNNEL_PORT)=' "$SETUP_FILE" || true)"
	cur_ssh="${SSH_HOST:-}" cur_lan="${HOME_LAN_HOST:-}"
	cur_port="${OLLAMA_LOCAL_PORT:-11434}" cur_tport="${OLLAMA_TUNNEL_PORT:-11112}"
	cur_rtport="${ROUTER_TUNNEL_PORT:-18080}"
fi
[[ -s $BROWSER_FILE ]] && cur_browser="$(head -n1 "$BROWSER_FILE")"

ask() { # ask <prompt> <current> -> prints the answer
	local prompt=$1 current=$2 answer=""
	if ((PROMPT)) && [[ -t 0 ]]; then
		read -r -p "  $prompt [${current:-—}]: " answer || true
	fi
	printf '%s' "${answer:-$current}"
}

if ((PROMPT && DRY == 0)); then
	say ""
	say "Machine-local values — Enter keeps the default, '-' clears it (feature off)."
	say ""
fi

ssh_host=$(ask "SSH host for remote aliases (user@host)" "$cur_ssh")
lan_host=$(ask "LAN host for the tunnel alias (router/other machine)" "$cur_lan")
ollama_port=$(ask "Local Ollama port" "$cur_port")
ollama_tport=$(ask "Tunnel port for Ollama" "$cur_tport")
router_port=$(ask "Tunnel port for LAN host:80" "$cur_rtport")
browser=$(ask "Browser bundle id for Hyper+W" "$cur_browser")

clean() { [[ $1 == - ]] && printf '' || printf '%s' "$1"; }
ssh_host=$(clean "$ssh_host")
lan_host=$(clean "$lan_host")
browser=$(clean "$browser")

# ── 4. write the local values ────────────────────────────────────────
if ((DRY)); then
	say "  + would write $SETUP_FILE"
else
	mkdir -p "$(dirname "$SETUP_FILE")"
	{
		printf '# Generated by install.sh — machine-local values, never committed.\n'
		printf '# Sourced by .zshrc; a missing value means the alias is not created.\n'
		[[ -n $ssh_host ]] && printf "export SSH_HOST='%s'\n" "$ssh_host"
		[[ -n $lan_host ]] && printf "export HOME_LAN_HOST='%s'\n" "$lan_host"
		[[ -n $ollama_port ]] && printf "export OLLAMA_LOCAL_PORT='%s'\n" "$ollama_port"
		[[ -n $ollama_tport ]] && printf "export OLLAMA_TUNNEL_PORT='%s'\n" "$ollama_tport"
		[[ -n $router_port ]] && printf "export ROUTER_TUNNEL_PORT='%s'\n" "$router_port"
	} >"$SETUP_FILE"
	chmod 600 "$SETUP_FILE"
	say "wrote $SETUP_FILE"
fi

if ((DRY)); then
	say "  + would write $BROWSER_FILE (${browser:-default $cur_browser})"
else
	mkdir -p "$(dirname "$BROWSER_FILE")"
	if [[ -n $browser ]]; then
		printf '%s\n' "$browser" >"$BROWSER_FILE"
		say "wrote $BROWSER_FILE ($browser)"
	else
		# no value -> no file, open-browser.sh falls back to Safari
		rm -f "$BROWSER_FILE"
		say "browser not set — Hyper+W falls back to com.apple.Safari"
	fi
fi

# ── 5. clear conflicts ───────────────────────────────────────────────
# Anything at a target path that is not already a link into this repo is moved
# aside (never deleted) so stow can create its own links.
conflicts=0
for pkg in "${PACKAGES[@]}"; do
	while IFS= read -r -d '' src; do
		rel="${src#"$REPO/$pkg/"}"
		target="$HOME/$rel"
		anc="$HOME"
		for part in $(printf '%s' "$rel" | tr '/' ' '); do
			anc="$anc/$part"
			[[ $anc == "$target" ]] && break
			if [[ -L $anc ]]; then
				run mkdir -p "$BACKUP/$(dirname "${anc#"$HOME/"}")"
				run mv "$anc" "$BACKUP/${anc#"$HOME/"}"
				say "moved aside dir symlink: ${anc#"$HOME/"}"
				conflicts=$((conflicts + 1))
			fi
		done
		[[ -e $target || -L $target ]] || continue
		if [[ -L $target ]]; then
			case "$(readlink "$target")" in
			"$REPO/$pkg/"*) continue ;;
			esac
		fi
		run mkdir -p "$BACKUP/$(dirname "$rel")"
		run mv "$target" "$BACKUP/$rel"
		say "moved aside: $rel"
		conflicts=$((conflicts + 1))
	done < <(find "$REPO/$pkg" -type f -print0)
done
((conflicts)) || say "no conflicts"

# ── 6. stow ──────────────────────────────────────────────────────────
say ""
say "stowing: ${PACKAGES[*]}"
if ((DRY)); then
	say "  + stow --no-folding -v -t $HOME -d $REPO ${PACKAGES[*]}"
else
	stow --no-folding -v -t "$HOME" -d "$REPO" "${PACKAGES[@]}"
fi

say ""
say "done. open a new shell (or: exec zsh)."
say "undo:  stow -D -t \"\$HOME\" -d \"$REPO\" ${PACKAGES[*]}"
say "moved aside (if any): $BACKUP"
